
CREATE TABLE pontos_coleta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    endereco VARCHAR(200) NOT NULL,
    bairro VARCHAR(100) NOT NULL,
    cidade VARCHAR(100) NOT NULL,
    cep VARCHAR(10),
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE residuos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    categoria VARCHAR(80) NOT NULL,
    descricao VARCHAR(255)
);

CREATE TABLE coletas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ponto_coleta_id BIGINT NOT NULL,
    residuo_id BIGINT NOT NULL,
    quantidade_kg DECIMAL(10,2) NOT NULL,
    data_coleta TIMESTAMP NOT NULL,
    status VARCHAR(30) NOT NULL,

    CONSTRAINT fk_coleta_ponto
        FOREIGN KEY (ponto_coleta_id)
        REFERENCES pontos_coleta(id),

    CONSTRAINT fk_coleta_residuo
        FOREIGN KEY (residuo_id)
        REFERENCES residuos(id)
);
